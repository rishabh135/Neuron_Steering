#!/usr/bin/env node
// Builds the portable artifact from the same sources as the local app.
//   node scripts/build_artifact.mjs            -> artifacts/NeuronSteeringArtifact.tsx   (paste into Claude.ai)
//                                                artifacts/dist/neuron-steering.html     (one self-contained HTML page)
// Requires `npm --prefix ui ci`. The .tsx imports only `react`; the CSS is compiled from the shared theme and inlined.
import { execFileSync } from "node:child_process"
import { createRequire } from "node:module"
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { pathToFileURL } from "node:url"

const root = path.resolve(import.meta.dirname, "..")
const ui = path.join(root, "ui")
const out = path.join(root, "artifacts")
mkdirSync(path.join(out, "dist"), { recursive: true })
const require_ = createRequire(path.join(ui, "package.json"))
const { build } = await import(pathToFileURL(require_.resolve("esbuild")).href)

// 1. Tailwind: compile only the classes the shared code uses.
const cli = path.join(path.dirname(require_.resolve("@tailwindcss/cli/package.json")), "dist/index.mjs")
const cssFile = path.join(out, "dist/artifact.css")
execFileSync(process.execPath, [cli, "-i", path.join(ui, "src/artifact/artifact.css"), "-o", cssFile, "--minify"], { cwd: ui, stdio: "inherit" })
const css = readFileSync(cssFile, "utf8")

const virtualCss = { name: "virtual-lab-css", setup(b) {
  b.onResolve({ filter: /^virtual:lab-css$/ }, () => ({ path: "lab-css", namespace: "lab-css" }))
  b.onLoad({ filter: /.*/, namespace: "lab-css" }, () => ({ contents: `export default ${JSON.stringify(css)}`, loader: "js" }))
} }
const common = { entryPoints: [path.join(ui, "src/artifact/entry.tsx")], bundle: true, plugins: [virtualCss], nodePaths: [path.join(ui, "node_modules")], absWorkingDir: ui,
  loader: { ".json": "json" }, logLevel: "warning", legalComments: "none" }

// 2. The pasteable component: React stays external; no other import survives.
const tsx = path.join(out, "NeuronSteeringArtifact.tsx")
const res = await build({ ...common, format: "esm", target: "es2020", external: ["react"], jsx: "transform", tsconfigRaw: { compilerOptions: { jsx: "react" } }, write: false, minify: false })
const body = res.outputFiles[0].text
const imports = [...body.matchAll(/^import .* from "([^"]+)"/gm)].map((m) => m[1])
const bad = imports.filter((m) => m !== "react")
if (bad.length) throw new Error("unsupported imports in artifact: " + bad.join(", "))
const header = `/* eslint-disable */
// @ts-nocheck
/**
 * One Prompt. Different Paths. - portable Claude Artifact.
 * GENERATED by scripts/build_artifact.mjs from ui/src/lab and ui/src/artifact. Edit those, then rebuild; do not edit here.
 * Imports: react only. No network, no localhost, no model: illustrative mode plus measured-run JSON import.
 * Source revision pins: neuron-explorer f79b2196, llama.cpp d854d98 (docs/SOURCE_AUDIT.json).
 */
import * as React from "react";
`
// esbuild keeps one import per bundled module; fold them into a single statement at the top.
const specs = new Set()
const folded = body.replace(/^import \* as React from "react";\n/m, "").replace(/^import \{([^}]+)\} from "react";\n/gm, (_, list) => { list.split(",").forEach((x) => specs.add(x.trim())); return "" })
writeFileSync(tsx, header + `import { ${[...specs].sort().join(", ")} } from "react";\n` + folded)

// 3. One self-contained HTML page (everything inlined) for hosting as an Artifact.
const mountEntry = path.join(out, "dist/mount.tsx")
writeFileSync(mountEntry, `import { createRoot } from "react-dom/client"\nimport App from ${JSON.stringify(tsx)}\ncreateRoot(document.getElementById("root")!).render(<App />)\n`)
const page = await build({ ...common, entryPoints: [mountEntry], format: "iife", target: "es2020", jsx: "automatic", write: false, minify: true, define: { "process.env.NODE_ENV": '"production"' } })
const pageJs = page.outputFiles[0].text.replace(/<\/script/gi, "<\\/script")
writeFileSync(path.join(out, "dist/neuron-steering.html"), `<!doctype html>
<html lang="en" data-theme="dark"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="color-scheme" content="dark light">
<title>One Prompt. Different Paths.</title><style>html,body{margin:0;background:#080b12}</style></head>
<body><div id="root"></div><script>${pageJs}</script></body></html>
`)
// The Artifact tool wraps a page in its own document skeleton, so it takes the same page without html/head/body tags.
writeFileSync(path.join(out, "dist/neuron-steering.artifact.html"), `<title>One Prompt. Different Paths.</title>
<style>html,body{margin:0;background:#080b12}</style>
<div id="root"></div>
<script>${pageJs}</script>
`)
console.log(`artifacts/NeuronSteeringArtifact.tsx ${(Buffer.byteLength(header + body) / 1024).toFixed(0)} KB; imports: ${[...new Set(imports)].join(", ")}`)
console.log(`artifacts/dist/neuron-steering.html ${(Buffer.byteLength(pageJs) / 1024).toFixed(0)} KB js`)
