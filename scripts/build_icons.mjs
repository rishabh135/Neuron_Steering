#!/usr/bin/env node
// Writes ui/src/lab/icons.tsx: the few lucide icons the shared chapters use, as dependency-free React components.
// The portable artifact may import only `react`, so the shared code must not import lucide-react.
// Icon geometry is from lucide-react (ISC licence, https://lucide.dev); run after `npm --prefix ui ci`.
import { writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { pathToFileURL } from "node:url"
import path from "node:path"

const ui = path.resolve(import.meta.dirname, "../ui")
const names = ["arrow-left", "arrow-right", "check", "copy", "download", "external-link", "eye", "eye-off", "file-code", "minus", "monitor", "moon", "pause", "play", "plus", "rotate-ccw", "skip-back", "skip-forward", "square", "sun", "upload"]
const req = createRequire(path.join(ui, "package.json"))
const root = path.dirname(req.resolve("lucide-react/package.json"))
const pascal = (s) => s.split("-").map((p) => p[0].toUpperCase() + p.slice(1)).join("")
let out = `// GENERATED by scripts/build_icons.mjs. Do not edit.
// Icon geometry: lucide-react ${JSON.parse((await import("node:fs")).readFileSync(path.join(root, "package.json"), "utf8")).version}, ISC licence, Copyright (c) Lucide Icons and Contributors.
import type { ReactElement, SVGProps } from "react"

export type IconProps = Omit<SVGProps<SVGSVGElement>, "ref"> & { size?: number }
const make = (body: ReactElement) => ({ size = 24, ...rest }: IconProps) => (
  <svg xmlns="http://www.w3.org/2000/svg" width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={2} strokeLinecap="round" strokeLinejoin="round" aria-hidden="true" focusable="false" {...rest}>{body}</svg>
)
`
for (const n of names) {
  const mod = await import(pathToFileURL(path.join(root, "dist/esm/icons", n + ".mjs")).href)
  const node = mod.__iconData.node
  const kids = node.map(([tag, attrs]) => {
    const props = Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => `${k.replace(/-([a-z])/g, (_, c) => c.toUpperCase())}=${JSON.stringify(String(v))}`).join(" ")
    return `<${tag} ${props} />`
  })
  out += `export const ${pascal(n)} = make(<>${kids.join("")}</>)\n`
}
writeFileSync(path.join(ui, "src/lab/icons.tsx"), out)
console.log("wrote ui/src/lab/icons.tsx", names.length, "icons")
